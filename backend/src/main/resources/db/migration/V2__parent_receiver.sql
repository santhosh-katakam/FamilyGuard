CREATE TABLE parent_receivers (
 id integer PRIMARY KEY CHECK(id=1),
 admin_id integer NOT NULL DEFAULT 1 CHECK(admin_id=1) REFERENCES admin_users(id),
 name varchar(80) NOT NULL,
 token_hash varchar(64) NOT NULL UNIQUE,
 expires_at timestamp with time zone NOT NULL,
 last_seen timestamp with time zone,
 cursor bigint NOT NULL DEFAULT 0,
 offered_cursor bigint NOT NULL DEFAULT 0
);
CREATE TABLE parent_delivery_events (
 sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id uuid NOT NULL UNIQUE,
 device_id uuid NOT NULL REFERENCES child_devices(id) ON DELETE CASCADE,
 category varchar(32) NOT NULL,
 kind varchar(32) NOT NULL,
 package_name varchar(255),
 occurred_at timestamp with time zone NOT NULL,
 received_at timestamp with time zone NOT NULL
);
CREATE INDEX parent_delivery_received_idx ON parent_delivery_events(received_at);
